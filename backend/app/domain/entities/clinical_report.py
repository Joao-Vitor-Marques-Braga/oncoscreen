"""Clinical report and guardrail assessment entities."""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import List

from app.domain.value_objects.risk_level import ConcordanceStatus, RiskLevel


@dataclass(frozen=True)
class GuardrailAssessment:
    """Deterministic clinical guardrail output comparing CNN vision vs. anamnesis."""

    clinical_score: int
    clinical_risk: RiskLevel
    cnn_positive: bool
    final_risk: RiskLevel
    concordance_status: ConcordanceStatus
    guardrail_triggered: bool
    alert_title: str
    alert_description: str
    triggered_red_flags: List[str] = field(default_factory=list)


@dataclass
class ClinicalReport:
    """Structured multimodal clinical report generated by the SLM + Guardrails."""

    markdown_body: str
    model_used: str
    generated_via_fallback: bool = False

